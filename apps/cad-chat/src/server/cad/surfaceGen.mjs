import { normalizeDraft, scalarParams } from "../../lib/surface/surfaceSchema.js";

export const SPEC_DECL_RE = /^SURFACE_SPEC\s*=\s*(\{[\s\S]*?^\})[ \t]*$/m;

// Match only unquoted tokens following an object colon or an array delimiter.
function convertLiterals(source, tokens, mapping) {
  const objectValue = new RegExp(`(:\\s*)(${tokens})(?=\\s*[,\\n\\]}])`, "g");
  const arrayValue = new RegExp(`(\\[\\s*|,\\s*)(${tokens})(?=\\s*[,\\]])`, "g");
  const replace = (_, prefix, token) => prefix + mapping[token];
  return source.replace(objectValue, replace).replace(arrayValue, replace);
}

const pyFloat = (n) => Number.isInteger(n) ? `${n}.0` : String(n);

export function compileSurfaceGenerator(draft, { name = "part" } = {}) {
  const spec = normalizeDraft(draft);
  const params = scalarParams(spec);
  const keys = ["thick", "fillet_r", "revolve_deg"].filter((key) => Object.hasOwn(params, key));
  const specLiteral = convertLiterals(JSON.stringify(spec, null, 1), "true|false|null", { true: "True", false: "False", null: "None" });
  const paramsLiteral = `{${keys.map((key) => `${JSON.stringify(key)}: ${pyFloat(params[key])}`).join(", ")}}`;
  const checks = keys.map((key) => key === "revolve_deg"
    ? `    if not (0 < p["revolve_deg"] <= 360):\n        raise ValueError(f"revolve_deg 必須在 (0, 360],目前 {p['revolve_deg']}")`
    : `    if p["${key}"] <= 0:\n        raise ValueError(f"${key} 必須 > 0,目前 {p['${key}']}")`).join("\n") || "    pass";
  return `# ${name}: generated by cad-chat product mode (surface-draft-v1).
# Do not hand-edit geometry: SURFACE_SPEC below is the single source of truth
# (the draft JSON); only PARAMS scalars are regenerated by the sliders.
from build123d import *
from cadpy.surface import SurfaceBuilder, check_surface_model

SURFACE_SPEC = ${specLiteral}

PARAMS = ${paramsLiteral}


def _check_params():
    p = PARAMS
${checks}


def gen_step():
    _check_params()
    return SurfaceBuilder(SURFACE_SPEC, PARAMS).build()


def check_geometry(shape):
    check_surface_model(shape, SURFACE_SPEC)
`;
}

export function readEmbeddedSpec(source) {
  try {
    const match = SPEC_DECL_RE.exec(source);
    if (!match) return null;
    return JSON.parse(convertLiterals(match[1], "True|False|None", { True: "true", False: "false", None: "null" }));
  } catch {
    return null;
  }
}
