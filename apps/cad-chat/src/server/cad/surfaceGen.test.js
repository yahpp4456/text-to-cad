test("all examples compile and embedded Python literals round-trip to normalized JSON", () => {
  for (const name of ["mouse_shell", "vase", "mickey"]) {
    const d = example(name);
    const before = structuredClone(d);
    const out = compileSurfaceGenerator(d);
    assert.deepStrictEqual(readEmbeddedSpec(out), normalizeDraft(d));
    assert.deepStrictEqual(d, before);
    assert.ok(out.startsWith("# part:"));
  }
  assert.ok(compileSurfaceGenerator(example("mouse_shell")).includes('"symmetry": "YZ"'));
  assert.ok(compileSurfaceGenerator(example("vase")).includes('"symmetry": None'));
});

test("draft with no scalars emits empty PARAMS and pass in the check body", () => {
  const d = minimal();
  d.result = "shell";
  d.ops = [];
  const out = compileSurfaceGenerator(d);
  assert.ok(out.includes("PARAMS = {}\n"));
  assert.ok(out.includes("def _check_params():\n    p = PARAMS\n    pass\n\n\n"));
  assert.deepStrictEqual(readEmbeddedSpec(out), normalizeDraft(d));
});

test("vase emits ordered float PARAMS and both scalar checks", () => {
  const out = compileSurfaceGenerator(example("vase"));
  assert.ok(out.includes('PARAMS = {"thick": 2.0, "revolve_deg": 360.0}'));
  assert.ok(out.includes(`    if p["thick"] <= 0:
        raise ValueError(f"thick 必須 > 0,目前 {p['thick']}")
    if not (0 < p["revolve_deg"] <= 360):
        raise ValueError(f"revolve_deg 必須在 (0, 360],目前 {p['revolve_deg']}")`));
});

test("literal conversion preserves quoted identifiers including true_edge", () => {
  const d = minimal();
  d.curves[0].id = "true_edge";
  d.surfaces[0].curve = "true_edge";
  for (const id of ["true", "false", "null"]) d.curves.push({ ...structuredClone(d.curves[0]), id });
  const out = compileSurfaceGenerator(d);
  assert.ok(out.includes('"id": "true_edge"'));
  const spec = readEmbeddedSpec(out);
  assert.equal(spec.curves[0].id, "true_edge");
  assert.deepStrictEqual(spec, normalizeDraft(d));
});

test("SPEC_DECL_RE captures the declaration ending with a column-zero brace", () => {
  const out = compileSurfaceGenerator(minimal());
  const match = SPEC_DECL_RE.exec(out);
  assert.ok(match);
  assert.ok(match[1].startsWith("{"));
  assert.ok(match[1].endsWith("\n}"));
  assert.equal(match[1].split("\n").at(-1), "}");
  assert.equal(match.index, out.indexOf("SURFACE_SPEC = {"));
});

test("invalid and partial drafts cannot compile and propagate DraftError", () => {
  for (const raw of [null, {}, { schemaVersion: 1, curves: [], surfaces: [] }]) {
    assert.throws(() => compileSurfaceGenerator(raw), DraftError);
  }
});

test("all scalar PARAMS and checks follow thick, fillet_r, revolve_deg order", () => {
  const d = example("vase");
  d.ops.unshift({ op: "fillet", r: 1.5 });
  const out = compileSurfaceGenerator(d);
  assert.ok(out.includes('PARAMS = {"thick": 2.0, "fillet_r": 1.5, "revolve_deg": 360.0}'));
  assert.ok(out.includes(`    if p["fillet_r"] <= 0:
        raise ValueError(f"fillet_r 必須 > 0,目前 {p['fillet_r']}")`));
  assert.ok(out.indexOf('if p["thick"]') < out.indexOf('if p["fillet_r"]'));
  assert.ok(out.indexOf('if p["fillet_r"]') < out.indexOf('if not (0 < p["revolve_deg"]'));
  assert.deepStrictEqual(readEmbeddedSpec(out), normalizeDraft(d));
});

test("readEmbeddedSpec returns null for absent or invalid declarations and reads the first", () => {
  for (const source of ["", "SURFACE_SPEC = []", "SURFACE_SPEC = {\n invalid\n}", "SURFACE_SPEC = {\n \"x\": True,\n}", null]) {
    assert.equal(readEmbeddedSpec(source), null);
  }
  const first = compileSurfaceGenerator(minimal());
  const second = compileSurfaceGenerator(example("vase"));
  assert.deepStrictEqual(readEmbeddedSpec(first + second), normalizeDraft(minimal()));
});

test("reading supports boolean and null array values without changing quoted tokens", () => {
  const source = `SURFACE_SPEC = {
 "values": [True, False, None],
 "nested": [[None, True], [False]],
 "quoted": ["True", "False", "None"],
 "True": "True"
}
`;
  assert.deepStrictEqual(readEmbeddedSpec(source), {
    values: [true, false, null], nested: [[null, true], [false]], quoted: ["True", "False", "None"], True: "True",
  });
});
